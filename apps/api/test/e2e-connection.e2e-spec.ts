import type { DataSource } from 'typeorm';
import {
  e2eConnectionOptions,
  e2eTarget,
  ScratchDatabases,
  withE2eEnv,
} from './support/e2e-connection';

// E2E isolation spec §4.2 ("Single connection helper"), §4.5 item 2,
// invariants 4 and 5. The admin connection is a stub: no database needed.

// Searched-for SQL keywords are assembled from fragments (spec §7 L512, N1).
const CREATE = ['CREATE', 'DATABASE'].join(' ');
const DROP = ['DROP', 'DATABASE'].join(' ');

interface StubAdmin {
  admin: DataSource;
  calls: string[];
}

function stubAdmin(): StubAdmin {
  const calls: string[] = [];
  const admin = {
    query: (sql: string) => {
      calls.push(sql);
      return Promise.resolve([]);
    },
  } as unknown as DataSource;
  return { admin, calls };
}

describe('ScratchDatabases', () => {
  it('generates 54-byte clensy_migration_<hex>_test names, each different', () => {
    const scratch = new ScratchDatabases();
    const a = scratch.generate();
    const b = scratch.generate();
    expect(a).toMatch(/^clensy_migration_[0-9a-f]{32}_test$/);
    expect(Buffer.byteLength(a)).toBe(54);
    expect(a).not.toBe(b);
  });

  describe.each(['create', 'drop'] as const)(
    '%s refuses, issuing nothing',
    (op) => {
      it('a name this instance did not generate', async () => {
        const { admin, calls } = stubAdmin();
        const scratch = new ScratchDatabases();
        await expect(
          scratch[op](admin, 'clensy_migration_' + '0'.repeat(32) + '_test'),
        ).rejects.toThrow('not generated by this registry');
        expect(calls).toEqual([]);
      });

      it('the E2E target, even when this instance generated it', async () => {
        const { admin, calls } = stubAdmin();
        const scratch = new ScratchDatabases();
        const name = scratch.generate();
        await withE2eEnv({ DB_NAME: name }, async () => {
          await expect(scratch[op](admin, name)).rejects.toThrow(
            'is the E2E target',
          );
        });
        expect(calls).toEqual([]);
      });

      it('clensy', async () => {
        const { admin, calls } = stubAdmin();
        await expect(
          new ScratchDatabases()[op](admin, 'clensy'),
        ).rejects.toThrow('not generated by this registry');
        expect(calls).toEqual([]);
      });

      it('a name generated by a different instance', async () => {
        const { admin, calls } = stubAdmin();
        const other = new ScratchDatabases().generate();
        await expect(new ScratchDatabases()[op](admin, other)).rejects.toThrow(
          'not generated by this registry',
        );
        expect(calls).toEqual([]);
      });
    },
  );

  it('create and drop each issue exactly one statement naming the quoted database', async () => {
    const { admin, calls } = stubAdmin();
    const scratch = new ScratchDatabases();
    const name = scratch.generate();
    await scratch.create(admin, name);
    await scratch.drop(admin, name);
    expect(calls).toHaveLength(2);
    expect(calls[0]).toContain(CREATE);
    expect(calls[0]).toContain(`"${name}"`);
    expect(calls[1]).toContain(DROP);
    expect(calls[1]).toContain(`"${name}"`);
  });
});

describe('e2eConnectionOptions', () => {
  it('rejects a non-Test database', () => {
    expect(() => e2eConnectionOptions('clensy')).toThrow();
  });

  it('returns the published target by default', () => {
    const options = e2eConnectionOptions();
    expect(options).toMatchObject({
      database: process.env.DB_NAME,
      host: process.env.DB_HOST,
      port: Number(process.env.DB_PORT),
      type: 'postgres',
      username: process.env.DB_USERNAME,
    });
  });
});

describe('e2eTarget', () => {
  it.each([[{ DB_NAME: undefined }], [{ DB_PORT: 'abc' }], [{ DB_HOST: '' }]])(
    'throws for %p',
    async (overrides) => {
      await withE2eEnv(overrides, () => {
        expect(() => e2eTarget()).toThrow();
      });
    },
  );
});

describe('withE2eEnv', () => {
  const KEY = 'E2E_CONNECTION_SPEC_PROBE';

  it('leaves an unset key unset, never the string "undefined"', async () => {
    delete process.env[KEY];
    await withE2eEnv({ [KEY]: 'x' }, () => {
      expect(process.env[KEY]).toBe('x');
    });
    expect(Object.hasOwn(process.env, KEY)).toBe(false);
  });

  it('restores an existing key after fn throws', async () => {
    process.env[KEY] = 'before';
    await expect(
      withE2eEnv({ [KEY]: 'during' }, () => {
        throw new Error('boom');
      }),
    ).rejects.toThrow('boom');
    expect(process.env[KEY]).toBe('before');
    delete process.env[KEY];
  });

  it('deletes a key for an undefined override inside fn', async () => {
    process.env[KEY] = 'before';
    await withE2eEnv({ [KEY]: undefined }, () => {
      expect(Object.hasOwn(process.env, KEY)).toBe(false);
    });
    expect(process.env[KEY]).toBe('before');
    delete process.env[KEY];
  });
});
