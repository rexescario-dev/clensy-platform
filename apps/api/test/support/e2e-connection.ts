import { randomBytes } from 'node:crypto';
import type { DataSource, DataSourceOptions } from 'typeorm';
import {
  type EffectiveConnectionSettings,
  isTestDatabaseName,
  validateEffectiveSettings,
} from '../../src/platform/database/effective-connection-settings';

// E2E isolation spec §4.2 ("Single connection helper") and §4.5 item 2.
// Every e2e connection is built here from the published target, and
// scratch databases are created and dropped only through ScratchDatabases
// (invariant 4). SQL keywords are assembled from fragments, so the static
// guard scan (spec §7) finds them only where they are allowed.

export type PostgresConnectionOptions = Extract<
  DataSourceOptions,
  { type: 'postgres' }
>;

const CREATE_DATABASE = ['CREATE', 'DATABASE'].join(' ');
const DROP_DATABASE_IF_EXISTS = ['DROP', 'DATABASE', 'IF', 'EXISTS'].join(' ');

export class ScratchDatabases {
  private readonly generated = new Set<string>();

  async create(admin: DataSource, name: string): Promise<void> {
    this.assertOwned(name);
    await admin.query(`${CREATE_DATABASE} ${quoteIdentifier(name)}`);
  }

  async drop(admin: DataSource, name: string): Promise<void> {
    this.assertOwned(name);
    await admin.query(`${DROP_DATABASE_IF_EXISTS} ${quoteIdentifier(name)}`);
  }

  generate(): string {
    const name = `clensy_migration_${randomBytes(16).toString('hex')}_test`;
    this.generated.add(name);
    return name;
  }

  private assertOwned(name: string): void {
    if (!this.generated.has(name)) {
      throw new Error(
        `scratch database ${JSON.stringify(name)} was not generated by this registry`,
      );
    }
    if (!isTestDatabaseName(name)) {
      throw new Error(
        `scratch database ${JSON.stringify(name)} fails the Test-database rule`,
      );
    }
    if (name === e2eTarget().database) {
      throw new Error(
        `scratch database ${JSON.stringify(name)} is the E2E target`,
      );
    }
  }
}

/** Connection options for the published E2E target, or one scratch database. */
export function e2eConnectionOptions(
  database?: string,
): PostgresConnectionOptions {
  const target = e2eTarget();
  if (database !== undefined && !isTestDatabaseName(database)) {
    throw new Error(
      `e2e connection to ${JSON.stringify(database)} refused: not a Test database`,
    );
  }
  return {
    database: database ?? target.database,
    host: target.host,
    password: target.password,
    port: target.port,
    type: 'postgres',
    username: target.username,
  };
}

/**
 * The published target, validated again. No defaults: if a value is
 * missing, the e2e setup did not run, and nothing may connect.
 */
export function e2eTarget(): EffectiveConnectionSettings {
  const settings = validateEffectiveSettings({
    database: process.env.DB_NAME,
    host: process.env.DB_HOST,
    password: process.env.DB_PASSWORD,
    port: process.env.DB_PORT,
    username: process.env.DB_USERNAME,
  });
  if (!isTestDatabaseName(settings.database)) {
    throw new Error(
      `published DB_NAME ${JSON.stringify(settings.database)} is not a Test database`,
    );
  }
  return settings;
}

/**
 * Runs `fn` with the given environment overrides, then restores them. An
 * `undefined` override deletes the key; keys that were absent are deleted
 * again afterwards (assigning `undefined` would store "undefined").
 */
export async function withE2eEnv<T>(
  overrides: Readonly<Record<string, string | undefined>>,
  fn: () => Promise<T> | T,
): Promise<T> {
  const saved = Object.keys(overrides).map((key) => ({
    key,
    present: Object.hasOwn(process.env, key),
    value: process.env[key],
  }));
  for (const [key, value] of Object.entries(overrides)) {
    if (value === undefined) {
      delete process.env[key];
    } else {
      process.env[key] = value;
    }
  }
  try {
    return await fn();
  } finally {
    for (const { key, present, value } of saved) {
      if (present) {
        process.env[key] = value;
      } else {
        delete process.env[key];
      }
    }
  }
}

function quoteIdentifier(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}
